function explicitDisplayName(value?: Record<string, unknown>) {
  for (const key of ["display_name", "displayName", "title", "label", "name"]) {
    if (typeof value?.[key] === "string" && value[key].trim()) return value[key].trim()
  }
}

function localizedName(name: string) {
  const normalized = name
    .replace(/[\/_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
  if (!normalized || /[\u4e00-\u9fff]/.test(normalized)) return normalized || name

  const words = normalized.toLowerCase().split(" ")
  const compactWords = words.filter((word, index) => index === 0 || word !== words[index - 1])
  if (compactWords.every((word) => wordLabels[word])) return compactWords.map((word) => wordLabels[word]).join("")

  const translated = phraseLabels
    .reduce((text, [pattern, label]) => text.replace(pattern, label), normalized)
    .replace(/\s+/g, " ")
    .trim()
  return name
}

export function agentDisplayName(name: string, options?: Record<string, unknown>) {
  const shortName = name.split("/").at(-1) ?? name
  const exact = exactAgentLabels[name] ?? exactAgentLabels[shortName]
  if (exact) return exact
  const explicit = explicitDisplayName(options)
  if (explicit && explicit !== name) return localizedName(explicit)
  return agentLabels[name] ?? agentLabels[shortName] ?? localizedName(name)
}

export function agentDescription(name: string, description?: string, options?: Record<string, unknown>) {
  const display = agentDisplayName(name, options)
  const category = typeof options?.category === "string" ? options.category : ""
  if (description && /[一-鿿]/.test(description)) return description
  if (category) return `内置${category} AI 员工，适合处理${display}相关任务。`
  if (description) return description
  return `适合处理${display}相关任务。`
}
export function skillDisplayName(name: string, data?: Record<string, unknown>) {
  const explicit = explicitDisplayName(data)
  if (explicit && explicit !== name) return localizedName(explicit)
  return skillLabels[name] ?? localizedName(name)
}
