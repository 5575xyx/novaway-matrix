/**
 * 生成 `src/dynamic-workflow/compiler/libs.generated.ts`。
 *
 * 工作流编译器走全虚拟 host（内存 Map，不读盘），所以 TS 标准库必须以字符串形态随包发布：
 * 打包成单文件 CLI 之后，磁盘上没有 `node_modules/typescript/lib`。本脚本把
 * `lib.es2022.d.ts` 及其 `/// <reference>` 闭包读出来、逐文件写成模板字面量。
 *
 * 用法：`bun run script/generate-dwf-libs.ts`。
 * 升级 typescript 之后重跑，并把结果一并提交。
 *
 * 为什么模板字面量而不是 JSON.stringify：后者把每个文件压成一行，git diff 与 review 全废。
 * 模板字面量保内容、保换行；内容里的反引号 / `${` / 反斜杠下面逐字符转义。
 */

import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"

const require = createRequire(import.meta.url)
const here = path.dirname(fileURLToPath(import.meta.url))

/** 入口：作者脚本拿到的 lib 就是它，闭包由它自己声明的 reference 决定。 */
const ENTRY = "lib.es2022.d.ts"

const tsPkg = require.resolve("typescript/package.json")
const tsLibDir = path.join(path.dirname(tsPkg), "lib")
const tsVersion = JSON.parse(fs.readFileSync(tsPkg, "utf8")).version as string

/** 反斜杠。用码点构造，免得这份源码自己的转义被各种编辑器/格式化工具改坏。 */
const BS = String.fromCharCode(92)
const BT = String.fromCharCode(96)

/**
 * 闭包：从入口出发，跟随 `/// <reference lib="…" />` 与 `/// <reference path="…" />`。
 * 深度优先、入口在前——与 TS 自己加载默认库的顺序一致，不依赖目录遍历顺序。
 */
function closure(entry: string): string[] {
  const seen = new Set<string>()
  const order: string[] = []
  const visit = (name: string) => {
    if (seen.has(name)) return
    seen.add(name)
    const file = path.join(tsLibDir, name)
    if (!fs.existsSync(file)) throw new Error(`missing lib file: ${name}`)
    const text = fs.readFileSync(file, "utf8")
    order.push(name)
    for (const match of text.matchAll(/\/\/\/\s*<reference\s+(lib|path)\s*=\s*"([^"]+)"/g)) {
      visit(match[1] === "lib" ? `lib.${match[2]!.toLowerCase()}.d.ts` : path.basename(match[2]!))
    }
  }
  visit(entry)
  return order
}

/**
 * 把一段文本写成**双引号字符串**或**模板字面量**。
 *
 * 短文本用双引号（单行，能直接看懂）；长文本用模板字面量（保换行，diff 友好）。
 * 两种都要转义：反斜杠、反引号、`${`。模板里的换行原样保留。
 */
function literal(text: string): string {
  if (!text.includes("\n")) return JSON.stringify(text)
  const escaped = text
    .split(BS)
    .join(BS + BS)
    .split(BT)
    .join(BS + BT)
    .split("${")
    .join(BS + "${")
  return BT + escaped + BT
}

const files = closure(ENTRY)
const lines: string[] = [
  "// AUTO-GENERATED by script/generate-dwf-libs.ts — 不要手改。",
  `// 来源：typescript@${tsVersion} 的 ${ENTRY} reference 闭包（${files.length} 个文件）。`,
  "// 升级 typescript 之后重跑生成脚本，并把本文件一并提交。",
  "",
  `export const LIB_TYPESCRIPT_VERSION = ${JSON.stringify(tsVersion)}`,
  "",
  "/** 默认 lib 入口：编译选项里 \`lib: [LIB_ENTRY]\`。 */",
  `export const LIB_ENTRY = ${JSON.stringify(ENTRY)}`,
  "",
  "/** 文件名（basename）→ 全文。虚拟 host 只查这张表，不碰磁盘。 */",
  "export const LIB_FILES: Record<string, string> = {",
]
for (const name of files) {
  const text = fs.readFileSync(path.join(tsLibDir, name), "utf8")
  lines.push(`  ${JSON.stringify(name)}: ${literal(text)},`)
}
lines.push("}", "")

const out = path.join(here, "..", "src", "dynamic-workflow", "compiler", "libs.generated.ts")
fs.writeFileSync(out, lines.join("\n"), "utf8")

const bytes = fs.statSync(out).size
console.log(`wrote ${out}`)
console.log(`  typescript ${tsVersion}, ${files.length} lib files, ${(bytes / 1024).toFixed(0)} KB`)
